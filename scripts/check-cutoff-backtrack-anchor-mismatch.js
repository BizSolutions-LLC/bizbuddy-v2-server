// scripts/check-cutoff-backtrack-anchor-mismatch.js
//
// Confirms the "backtrack" cutoff-period generation bug for the Driver/Aide
// department: DepartmentCutoffSettings.startDate is Jan 7, 2026 (bi-weekly),
// but generatePeriodsBetweenDates() (src/services/Cutoff/cutoffGenerationService.js)
// uses the raw fromDate the client sends for historical/backtrack generation
// as the first period's periodStart verbatim, instead of snapping it to the
// settings.startDate anchor. This produces periods like Jan 1-14 instead of
// Jan 7-20, and can create periods that overlap with correctly-anchored ones
// generated by the normal forward path (generatePeriodDates()).
//
// This script:
//   1. Loads DepartmentCutoffSettings for the given department (default:
//      the Driver/Aide department, matched by name) to get the true anchor.
//   2. Loads all CutoffPeriod rows for that department, ordered by periodStart.
//   3. Flags any period whose periodStart isn't settings.startDate + 14n days
//      (bi-weekly cadence) as a MISMATCH.
//   4. Flags any pair of consecutive periods (by periodStart) that overlap.
//
// READ-ONLY — no writes.
//
// Usage:
//   node scripts/check-cutoff-backtrack-anchor-mismatch.js [departmentId-or-name]

const { PrismaClient } = require("@prisma/client");
const prisma = new PrismaClient();

const DEFAULT_DEPARTMENT_NAME = "Driver/Aide";
const MS_PER_DAY = 24 * 60 * 60 * 1000;

function fmt(date) {
  return date.toISOString().slice(0, 10);
}

async function main() {
  const arg = process.argv[2] || null;

  const settings = await prisma.departmentCutoffSettings.findFirst({
    where: arg
      ? { OR: [{ departmentId: arg }, { department: { name: arg } }] }
      : { department: { name: DEFAULT_DEPARTMENT_NAME } },
    include: { department: true },
  });

  if (!settings) {
    console.log(
      arg
        ? `No DepartmentCutoffSettings found for departmentId or name="${arg}"`
        : `No DepartmentCutoffSettings found for department name="${DEFAULT_DEPARTMENT_NAME}"`
    );
    return;
  }

  const anchor = new Date(settings.startDate);
  anchor.setHours(0, 0, 0, 0);

  console.log(`=== Department: ${settings.department?.name || "(unknown)"} (${settings.departmentId}) ===`);
  console.log(`Company: ${settings.companyId}`);
  console.log(`Frequency: ${settings.frequency}`);
  console.log(`Configured Starting Date (anchor): ${fmt(anchor)}`);
  console.log("");

  const periods = await prisma.cutoffPeriod.findMany({
    where: { companyId: settings.companyId, departmentId: settings.departmentId },
    orderBy: { periodStart: "asc" },
    select: {
      id: true,
      periodStart: true,
      periodEnd: true,
      frequency: true,
      status: true,
      isAutoGenerated: true,
      createdAt: true,
    },
  });

  console.log(`=== ${periods.length} CutoffPeriod row(s) found ===\n`);

  const cadenceDays = settings.frequency === "bi-weekly" ? 14 : null;
  let mismatchCount = 0;

  for (const p of periods) {
    const start = new Date(p.periodStart);
    start.setHours(0, 0, 0, 0);

    let flag = "N/A (non-bi-weekly frequency, not checked)";
    if (cadenceDays) {
      const daysSinceAnchor = Math.round((start - anchor) / MS_PER_DAY);
      const isMultiple = daysSinceAnchor >= 0 && daysSinceAnchor % cadenceDays === 0;
      flag = isMultiple
        ? `MATCH (offset ${daysSinceAnchor}d from anchor)`
        : `MISMATCH (offset ${daysSinceAnchor}d from anchor — not a multiple of ${cadenceDays})`;
      if (!isMultiple) mismatchCount++;
    }

    console.log(
      `${p.id} | ${fmt(p.periodStart)} -> ${fmt(p.periodEnd)} | status=${p.status} | ` +
        `autoGenerated=${p.isAutoGenerated} | createdAt=${p.createdAt.toISOString()} | ${flag}`
    );
  }

  console.log(`\n=== Anchor mismatches: ${mismatchCount} ===`);

  console.log(`\n=== Overlap check ===`);
  let overlapCount = 0;
  for (let i = 1; i < periods.length; i++) {
    const prev = periods[i - 1];
    const curr = periods[i];
    if (new Date(curr.periodStart) < new Date(prev.periodEnd)) {
      overlapCount++;
      console.log(
        `OVERLAP: [${fmt(prev.periodStart)} -> ${fmt(prev.periodEnd)}] (${prev.id}) ` +
          `overlaps with [${fmt(curr.periodStart)} -> ${fmt(curr.periodEnd)}] (${curr.id})`
      );
    }
  }
  if (overlapCount === 0) {
    console.log("No overlapping periods found.");
  } else {
    console.log(`\nTotal overlapping pairs: ${overlapCount}`);
  }
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
