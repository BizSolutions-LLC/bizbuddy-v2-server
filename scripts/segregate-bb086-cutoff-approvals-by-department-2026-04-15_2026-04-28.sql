-- ═════════════════════════════════════════════════════════════════════════
-- 3. APPLY — single DO block = single transaction (all or nothing)
--    EDIT v_expected (sum of will_move from 1b).
--    STAGED RUN: first set v_only_user to ONE employee's User.id and v_expected to that
--    employee's will_move count, check the Cutoff screen, then set v_only_user := NULL
--    and re-run for everyone (v_expected = the remaining will_move total).
-- ═════════════════════════════════════════════════════════════════════════

DO $$
DECLARE
  v_period_ids text[] := ARRAY[
    'cc4b3c34-b097-4a8c-b199-808c28550d60',
    'cutoff_cmnfnf2ol04pwnr4uay7tg96o_1789093107176_kqucxy2a5',
    'cutoff_cmnfni0bm04r8nr4us57sjcsk_1789093134626_5coekt31k',
    'cutoff_cmnfnklgt04sdnr4u153i8a0z_1789093124968_yff7zxanr'
  ];
  v_expected  integer := NULL;   -- <<< EDIT ME: number of approvals that should move
  v_only_user text    := NULL;   -- <<< optional: a single User.id for the staged first run
  v_bad       integer;
  v_moved     integer;
  v_ot_moved  integer;
  v_ot_skip   integer;
BEGIN
  IF v_expected IS NULL THEN
    RAISE EXCEPTION 'Fill in v_expected from the preview (sum of will_move). Nothing changed.';
  END IF;

  -- Users whose approvals / OT blocks sit in these periods (optionally just one user)
  CREATE TEMP TABLE _seg_users ON COMMIT DROP AS
  SELECT DISTINCT u.id, u."departmentId"
  FROM "User" u
  WHERE (v_only_user IS NULL OR u.id = v_only_user)
    AND (
      EXISTS (
        SELECT 1 FROM "TimeLog" t
        JOIN "TimeLogApproval" a ON a."timeLogId" = t.id
        WHERE t."userId" = u.id AND a."cutoffPeriodId" = ANY (v_period_ids)
      )
      OR EXISTS (
        SELECT 1 FROM "CutoffOtBlock" b
        WHERE b."userId" = u.id AND b."cutoffPeriodId" = ANY (v_period_ids)
      )
    );

  -- Guard 1: every affected user must have a department
  SELECT COUNT(*) INTO v_bad FROM _seg_users WHERE "departmentId" IS NULL;
  IF v_bad > 0 THEN
    RAISE EXCEPTION '% affected user(s) have no departmentId (see preview 1c). Nothing changed.', v_bad;
  END IF;

  -- Guard 2: every affected department must map to exactly ONE of the 4 periods
  SELECT COUNT(*) INTO v_bad
  FROM (SELECT DISTINCT "departmentId" AS d FROM _seg_users) x
  WHERE (SELECT COUNT(*) FROM "CutoffPeriod" cp
         WHERE cp.id = ANY (v_period_ids) AND cp."departmentId" = x.d) <> 1;
  IF v_bad > 0 THEN
    RAISE EXCEPTION '% department(s) have 0 or >1 candidate periods (see preview 1a). Nothing changed.', v_bad;
  END IF;

  -- Move approvals to the period of the user's department
  UPDATE "TimeLogApproval" a
  SET "cutoffPeriodId" = cp.id
  FROM "TimeLog" t, _seg_users su, "CutoffPeriod" cp
  WHERE t.id = a."timeLogId"
    AND su.id = t."userId"
    AND a."cutoffPeriodId" = ANY (v_period_ids)
    AND cp.id = ANY (v_period_ids)
    AND cp."departmentId" = su."departmentId"
    AND a."cutoffPeriodId" <> cp.id;
  GET DIAGNOSTICS v_moved = ROW_COUNT;

  -- Guard 3: moved count must match what the preview said
  IF v_moved <> v_expected THEN
    RAISE EXCEPTION 'Moved % approvals but v_expected = %. Rolling back, nothing changed.', v_moved, v_expected;
  END IF;

  -- OT blocks: same re-point, skipping any that would collide on (cutoffPeriodId, userId, date)
  SELECT COUNT(*) INTO v_ot_skip
  FROM "CutoffOtBlock" b
  JOIN _seg_users su ON su.id = b."userId"
  JOIN "CutoffPeriod" cp ON cp.id = ANY (v_period_ids) AND cp."departmentId" = su."departmentId"
  WHERE b."cutoffPeriodId" = ANY (v_period_ids)
    AND b."cutoffPeriodId" <> cp.id
    AND EXISTS (SELECT 1 FROM "CutoffOtBlock" x
                WHERE x."cutoffPeriodId" = cp.id AND x."userId" = b."userId" AND x."date" = b."date");

  UPDATE "CutoffOtBlock" b
  SET "cutoffPeriodId" = cp.id
  FROM _seg_users su, "CutoffPeriod" cp
  WHERE su.id = b."userId"
    AND b."cutoffPeriodId" = ANY (v_period_ids)
    AND cp.id = ANY (v_period_ids)
    AND cp."departmentId" = su."departmentId"
    AND b."cutoffPeriodId" <> cp.id
    AND NOT EXISTS (SELECT 1 FROM "CutoffOtBlock" x
                    WHERE x."cutoffPeriodId" = cp.id AND x."userId" = b."userId" AND x."date" = b."date");
  GET DIAGNOSTICS v_ot_moved = ROW_COUNT;

  RAISE NOTICE 'Moved % approvals; moved % OT blocks; skipped % OT blocks (would collide, left in place).',
    v_moved, v_ot_moved, v_ot_skip;
END $$;


-- ═════════════════════════════════════════════════════════════════════════
-- 4. POST-CHECK (SELECT only)
--    Expect: each department's period holds its own approvals, cc4b3c34 shows 0
--    (unless you ran the staged single-user pass).
-- ═════════════════════════════════════════════════════════════════════════

SELECT cp.id, d.name AS department,
       (SELECT COUNT(*) FROM "TimeLogApproval" a WHERE a."cutoffPeriodId" = cp.id) AS approvals,
       (SELECT COUNT(*) FROM "CutoffOtBlock"  b WHERE b."cutoffPeriodId" = cp.id) AS ot_blocks
FROM "CutoffPeriod" cp
LEFT JOIN "Department" d ON d.id = cp."departmentId"
WHERE cp.id IN (
  'cc4b3c34-b097-4a8c-b199-808c28550d60',
  'cutoff_cmnfnf2ol04pwnr4uay7tg96o_1789093107176_kqucxy2a5',
  'cutoff_cmnfni0bm04r8nr4us57sjcsk_1789093134626_5coekt31k',
  'cutoff_cmnfnklgt04sdnr4u153i8a0z_1789093124968_yff7zxanr'
)
ORDER BY cp."createdAt";

-- Any approval still pointing at a period of a DIFFERENT department than its user's?
SELECT COUNT(*) AS still_misplaced
FROM "TimeLogApproval" a
JOIN "TimeLog" t ON t.id = a."timeLogId"
JOIN "User" u ON u.id = t."userId"
JOIN "CutoffPeriod" cp ON cp.id = a."cutoffPeriodId"
WHERE a."cutoffPeriodId" IN (
  'cc4b3c34-b097-4a8c-b199-808c28550d60',
  'cutoff_cmnfnf2ol04pwnr4uay7tg96o_1789093107176_kqucxy2a5',
  'cutoff_cmnfni0bm04r8nr4us57sjcsk_1789093134626_5coekt31k',
  'cutoff_cmnfnklgt04sdnr4u153i8a0z_1789093124968_yff7zxanr'
)
  AND cp."departmentId" IS DISTINCT FROM u."departmentId";


