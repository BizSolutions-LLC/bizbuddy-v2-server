-- BB-086 follow-up: segregate the 2026-04-15..2026-04-28 cutoff approvals by department.
--
-- Problem: Piedmont Adult Day Program (company cmnegwuxm0004rf7fzo6wjrw2) has FOUR open
-- CutoffPeriods for 04-15..04-28 — three per-department `cutoff_cmnf…` periods plus a stray
-- `cc4b3c34-…` — and TimeLogApproval / CutoffOtBlock rows are spread across them.
-- Goal: every approval / OT block points at the ONE period that belongs to its user's
-- department (User.departmentId = CutoffPeriod.departmentId), leaving cc4b3c34 empty.
--
-- NOT run by Claude. Run it yourself, section by section, in order:
--   1. PREVIEW      (SELECT only)  — read it, note the approval count that WILL move
--   2. BACKUP       (creates _bak_ tables) — rollback path; fails if they already exist
--   3. APPLY        (one DO block = one transaction) — fill in v_expected first
--   4. POST-CHECK   (SELECT only)
--
-- Safety built into section 3 (any failure raises and changes NOTHING):
--   - aborts if v_expected is not filled in, or the moved-row count differs from it
--   - aborts if any affected user has no department
--   - aborts if any affected department has 0 or >1 candidate periods (e.g. cc4b3c34 itself
--     carries a departmentId that duplicates one of the others)
--   - v_only_user lets you fix ONE confirmed employee first (staged), then re-run for all
--
-- Not done here: cc4b3c34 is NOT deleted. Once section 4 shows it empty, deleting it is a
-- separate follow-up. CutoffOtBlock rows that would collide on the unique key
-- (cutoffPeriodId, userId, date) are skipped and reported, never overwritten.
--
-- Ordering caveat: if the TimeLog delete for this range already ran, its approvals were
-- cascade-deleted and there is nothing to move — run this AFTER the Backtrack re-import.
--
-- Rollback: restore from the _bak_ tables (see the end of the file), then DROP them.

-- The four period ids involved (from the delete dry-run). Edit here if they differ.
--   cc4b3c34-b097-4a8c-b199-808c28550d60
--   cutoff_cmnfnf2ol04pwnr4uay7tg96o_1789093107176_kqucxy2a5
--   cutoff_cmnfni0bm04r8nr4us57sjcsk_1789093134626_5coekt31k
--   cutoff_cmnfnklgt04sdnr4u153i8a0z_1789093124968_yff7zxanr


-- ═════════════════════════════════════════════════════════════════════════
-- 1. PREVIEW (SELECT only)
-- ═════════════════════════════════════════════════════════════════════════

-- 1a. The periods and which department each belongs to
SELECT cp.id, cp."departmentId", d.name AS department, cp."periodStart", cp."periodEnd", cp.status,
       cp."isAutoGenerated", cp."createdAt"
FROM "CutoffPeriod" cp
LEFT JOIN "Department" d ON d.id = cp."departmentId"
WHERE cp.id IN (
  'cc4b3c34-b097-4a8c-b199-808c28550d60',
  'cutoff_cmnfnf2ol04pwnr4uay7tg96o_1789093107176_kqucxy2a5',
  'cutoff_cmnfni0bm04r8nr4us57sjcsk_1789093134626_5coekt31k',
  'cutoff_cmnfnklgt04sdnr4u153i8a0z_1789093124968_yff7zxanr'
)
ORDER BY cp."createdAt";

-- 1b. Where the approvals are now vs. where they belong (rows where current <> target will move)
SELECT a."cutoffPeriodId"          AS current_period,
       u."departmentId"            AS user_department,
       d.name                      AS department,
       tp.id                       AS target_period,
       COUNT(*)                    AS approvals,
       COUNT(*) FILTER (WHERE tp.id IS DISTINCT FROM a."cutoffPeriodId") AS will_move
FROM "TimeLogApproval" a
JOIN "TimeLog" t ON t.id = a."timeLogId"
JOIN "User" u ON u.id = t."userId"
LEFT JOIN "Department" d ON d.id = u."departmentId"
LEFT JOIN "CutoffPeriod" tp
       ON tp."departmentId" = u."departmentId"
      AND tp.id IN (
        'cc4b3c34-b097-4a8c-b199-808c28550d60',
        'cutoff_cmnfnf2ol04pwnr4uay7tg96o_1789093107176_kqucxy2a5',
        'cutoff_cmnfni0bm04r8nr4us57sjcsk_1789093134626_5coekt31k',
        'cutoff_cmnfnklgt04sdnr4u153i8a0z_1789093124968_yff7zxanr'
      )
WHERE a."cutoffPeriodId" IN (
  'cc4b3c34-b097-4a8c-b199-808c28550d60',
  'cutoff_cmnfnf2ol04pwnr4uay7tg96o_1789093107176_kqucxy2a5',
  'cutoff_cmnfni0bm04r8nr4us57sjcsk_1789093134626_5coekt31k',
  'cutoff_cmnfnklgt04sdnr4u153i8a0z_1789093124968_yff7zxanr'
)
GROUP BY a."cutoffPeriodId", u."departmentId", d.name, tp.id
ORDER BY d.name, a."cutoffPeriodId";
-- Read the sum of `will_move` — that is the number to put in v_expected in section 3.
-- Any row with a NULL user_department or NULL target_period will make section 3 abort:
-- fix that first (assign the user a department / check the period's departmentId).

-- 1c. Any user in these periods with no department?
SELECT DISTINCT u.id, u.email
FROM "TimeLogApproval" a
JOIN "TimeLog" t ON t.id = a."timeLogId"
JOIN "User" u ON u.id = t."userId"
WHERE a."cutoffPeriodId" IN (
  'cc4b3c34-b097-4a8c-b199-808c28550d60',
  'cutoff_cmnfnf2ol04pwnr4uay7tg96o_1789093107176_kqucxy2a5',
  'cutoff_cmnfni0bm04r8nr4us57sjcsk_1789093134626_5coekt31k',
  'cutoff_cmnfnklgt04sdnr4u153i8a0z_1789093124968_yff7zxanr'
)
  AND u."departmentId" IS NULL;

-- 1d. OT blocks in these periods (moved along with approvals in section 3)
SELECT b."cutoffPeriodId", COUNT(*) AS ot_blocks
FROM "CutoffOtBlock" b
WHERE b."cutoffPeriodId" IN (
  'cc4b3c34-b097-4a8c-b199-808c28550d60',
  'cutoff_cmnfnf2ol04pwnr4uay7tg96o_1789093107176_kqucxy2a5',
  'cutoff_cmnfni0bm04r8nr4us57sjcsk_1789093134626_5coekt31k',
  'cutoff_cmnfnklgt04sdnr4u153i8a0z_1789093124968_yff7zxanr'
)
GROUP BY b."cutoffPeriodId";


-- ═════════════════════════════════════════════════════════════════════════
-- 2. BACKUP (rollback path) — copies EVERY approval / OT block in the 4 periods
--    (a superset of what will move). Errors if the tables already exist: drop the old
--    ones first only if you are sure you no longer need them.
-- ═════════════════════════════════════════════════════════════════════════

CREATE TABLE "_bak_bb086_tla_2026_04_15_28" AS
SELECT * FROM "TimeLogApproval"
WHERE "cutoffPeriodId" IN (
  'cc4b3c34-b097-4a8c-b199-808c28550d60',
  'cutoff_cmnfnf2ol04pwnr4uay7tg96o_1789093107176_kqucxy2a5',
  'cutoff_cmnfni0bm04r8nr4us57sjcsk_1789093134626_5coekt31k',
  'cutoff_cmnfnklgt04sdnr4u153i8a0z_1789093124968_yff7zxanr'
