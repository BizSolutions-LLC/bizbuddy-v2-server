// scripts/check-payment-date-jun24-cutoff.js
// Diagnostic: Jun 24 - Jul 7, 2026 cutoff periods show paymentDate = Jul 12 for
// Staff / Staff Supervisor but Jul 10 for Driver/Aide. Confirm whether this is
// caused by different DepartmentCutoffSettings.paymentOffsetDays per department.

const { PrismaClient } = require("@prisma/client");
const prisma = new PrismaClient();

async function main() {
  const driverAideDept = await prisma.department.findFirst({
    where: { name: { contains: "Driver", mode: "insensitive" } },
    select: { companyId: true, name: true },
  });

  if (!driverAideDept) {
    console.log("No department matching 'Driver' found. Aborting.");
    return;
  }

  const companyId = driverAideDept.companyId;
  console.log("Matched department:", driverAideDept.name);
  console.log("companyId:", companyId);

  const departments = await prisma.department.findMany({
    where: { companyId },
    select: { id: true, name: true },
  });
  console.log("\nDepartments:", departments);

  const settings = await prisma.departmentCutoffSettings.findMany({
    where: { companyId },
    include: { department: { select: { name: true } } },
  });

  console.log("\nDepartmentCutoffSettings rows:");
  for (const s of settings) {
    console.log(
      `  dept=${s.department?.name ?? "COMPANY-WIDE(null)"} departmentId=${s.departmentId} frequency=${s.frequency} paymentOffsetDays=${s.paymentOffsetDays} isActive=${s.isActive} startDate=${s.startDate?.toISOString().slice(0, 10)}`
    );
  }

  const periods = await prisma.cutoffPeriod.findMany({
    where: {
      companyId,
      periodStart: new Date("2026-06-24T00:00:00.000Z"),
    },
    include: { department: { select: { name: true } } },
    orderBy: { departmentId: "asc" },
  });

  console.log("\nCutoffPeriod rows for periodStart=2026-06-24:");
  for (const p of periods) {
    console.log(
      `  id=${p.id} dept=${p.department?.name ?? "COMPANY-WIDE(null)"} departmentId=${p.departmentId} periodStart=${p.periodStart.toISOString().slice(0, 10)} periodEnd=${p.periodEnd.toISOString().slice(0, 10)} paymentDate=${p.paymentDate.toISOString().slice(0, 10)} frequency=${p.frequency} isAutoGenerated=${p.isAutoGenerated} status=${p.status}`
    );
  }
}

main()
  .catch((e) => console.error(e))
  .finally(() => prisma.$disconnect());
