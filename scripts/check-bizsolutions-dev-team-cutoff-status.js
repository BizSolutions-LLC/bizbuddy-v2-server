// scripts/check-bizsolutions-dev-team-cutoff-status.js
//
// Which cutoff periods of BizSolutions LLC's "Development Team" department are
// Processed (and which are still open / locked)?
//
// A cutoff becomes "processed" only through PATCH /api/cutoff-periods/:id/status
// (cutoffPeriodController.updateCutoffStatus). Processed is final: the status can't
// change after that. There is no processedAt / processedBy column, so:
//   - "last change" = CutoffPeriod.updatedAt (when the row was last touched,
//     usually the status change);
//   - "payroll export" = the department's PayrollExport rows for that period
//     (written when it was set to processed, BB-066) and their generatedAt.
//     A processed period with no export rows means the export failed or the
//     period was processed before BB-066.
// Company-wide periods (no department) are listed too, because they also cover
// the Development Team employees.
//
// READ-ONLY: no writes. Raw SQL, so it works with any generated Prisma client.
//
// Usage:
//   node scripts/check-bizsolutions-dev-team-cutoff-status.js
//   node scripts/check-bizsolutions-dev-team-cutoff-status.js --department <departmentId>
//   node scripts/check-bizsolutions-dev-team-cutoff-status.js --status processed
//
//   --department  use this department id instead of finding "Development Team" by name
//   --status      only list periods with this status (open | locked | processed)

const moment = require("moment-timezone");
const { PrismaClient } = require("@prisma/client");
const prisma = new PrismaClient();

const COMPANY_ID = "cmvrxp9y0000grf5071x2nqvx"; // BizSolutions LLC (by id, never by name)
const DEPARTMENT_NAME = "Development Team";

function arg(name) {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 ? process.argv[i + 1] : undefined;
}

async function main() {
  const deptArg = arg("department");
  const statusArg = arg("status");
  if (statusArg && !["open", "locked", "processed"].includes(statusArg)) {
    throw new Error("--status must be open, locked or processed");
  }

  const [company] = await prisma.$queryRaw`
    SELECT "id", "name", "timeZone" FROM "Company" WHERE "id" = ${COMPANY_ID}`;
  if (!company) {
    console.log(`Company ${COMPANY_ID} not found.`);
    return;
  }
  const tz = company.timeZone || "America/Los_Angeles";
  // Cutoff dates are stored as UTC-midnight calendar dates: read the UTC date.
  const fmt = (d) => (d ? new Date(d).toISOString().slice(0, 10) : "-");
  const fmtTime = (d) => (d ? moment.tz(d, tz).format("YYYY-MM-DD HH:mm") : "-");
  const dateOnly = (d) => (d ? new Date(d).toISOString().slice(0, 10) : "-");

  const departments = deptArg
    ? await prisma.$queryRaw`
        SELECT "id", "name" FROM "Department" WHERE "id" = ${deptArg} AND "companyId" = ${COMPANY_ID}`
    : await prisma.$queryRaw`
        SELECT "id", "name" FROM "Department"
        WHERE "companyId" = ${COMPANY_ID} AND LOWER(TRIM("name")) = LOWER(${DEPARTMENT_NAME})`;

  console.log(`\n${company.name} (${company.id}), zone ${tz}`);
  if (!departments.length) {
    const all = await prisma.$queryRaw`
      SELECT "id", "name" FROM "Department" WHERE "companyId" = ${COMPANY_ID} ORDER BY "name"`;
    console.log(`Department "${deptArg || DEPARTMENT_NAME}" not found. Departments in this company:`);
    all.forEach((d) => console.log(`  ${d.name} (${d.id})`));
    console.log("Rerun with --department <id>.");
    return;
  }
  if (departments.length > 1) {
    console.log(`More than one department matches "${DEPARTMENT_NAME}":`);
    departments.forEach((d) => console.log(`  ${d.name} (${d.id})`));
    console.log("Rerun with --department <id>.");
    return;
  }
  const dept = departments[0];

  const [{ members }] = await prisma.$queryRaw`
    SELECT COUNT(*)::int AS "members" FROM "User"
    WHERE "departmentId" = ${dept.id} AND "isSystemAgent" = false`;
  console.log(`Department: ${dept.name} (${dept.id}), ${members} employee(s)`);

  const periods = await prisma.$queryRaw`
    SELECT cp."id", cp."departmentId", cp."periodStart", cp."periodEnd", cp."paymentDate",
           cp."frequency", cp."status", cp."isAutoGenerated", cp."createdAt", cp."updatedAt"
    FROM "CutoffPeriod" cp
    WHERE cp."companyId" = ${COMPANY_ID}
      AND (cp."departmentId" = ${dept.id} OR cp."departmentId" IS NULL)
    ORDER BY cp."periodStart" DESC`;

  const shown = statusArg ? periods.filter((p) => p.status === statusArg) : periods;
  if (!shown.length) {
    console.log(statusArg ? `No ${statusArg} cutoff periods.` : "No cutoff periods.");
    return;
  }

  const counts = { open: 0, locked: 0, processed: 0, other: 0 };
  console.log("");
  for (const p of shown) {
    counts[p.status in counts ? p.status : "other"]++;

    const approvals = await prisma.$queryRaw`
      SELECT "status", COUNT(*)::int AS "n" FROM "TimeLogApproval"
      WHERE "cutoffPeriodId" = ${p.id} GROUP BY "status"`;
    const approvalTxt = approvals.length
      ? approvals.map((a) => `${a.status} ${a.n}`).join(", ")
      : "none";

    const [exp] = await prisma.$queryRaw`
      SELECT COUNT(*)::int AS "rows", MAX("generatedAt") AS "generatedAt"
      FROM "PayrollExport"
      WHERE "companyId" = ${COMPANY_ID}
        AND "periodStart" = ${dateOnly(p.periodStart)}::date
        AND "periodEnd" = ${dateOnly(p.periodEnd)}::date
        AND "departmentId" IS NOT DISTINCT FROM ${p.departmentId}`;

    const mark = p.status === "processed" ? "✅ PROCESSED" : p.status.toUpperCase();
    const scope = p.departmentId ? dept.name : "company-wide (no department)";
    console.log(`[${mark}] ${fmt(p.periodStart)} → ${fmt(p.periodEnd)} | pay ${fmt(p.paymentDate)} | ${p.frequency} | ${scope}`);
    console.log(`    id ${p.id} | ${p.isAutoGenerated ? "auto-generated" : "created by hand"} ${fmtTime(p.createdAt)} | last change ${fmtTime(p.updatedAt)}`);
    console.log(`    approvals: ${approvalTxt}`);
    if (p.status === "processed") {
      console.log(
        exp.rows
          ? `    payroll export: ${exp.rows} employee row(s), generated ${fmtTime(exp.generatedAt)}`
          : "    payroll export: NONE (export failed, or processed before BB-066)"
      );
    } else if (exp.rows) {
      console.log(`    payroll export rows exist (${exp.rows}) although not processed`);
    }
  }

  console.log("\nTotals:");
  console.log(`  processed: ${counts.processed}, locked: ${counts.locked}, open: ${counts.open}${counts.other ? `, other: ${counts.other}` : ""}`);
  const latestProcessed = periods.find((p) => p.status === "processed");
  console.log(
    latestProcessed
      ? `  latest processed: ${fmt(latestProcessed.periodStart)} → ${fmt(latestProcessed.periodEnd)} (pay ${fmt(latestProcessed.paymentDate)})`
      : "  no processed period yet"
  );
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
